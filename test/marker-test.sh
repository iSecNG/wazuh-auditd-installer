#!/usr/bin/env bash
# Checks that uninstall's marker patterns match BOTH the pre-rename
# Checks that uninstall still recognises markers from BOTH the pre-rename
# (wazuh-auditd-installer) and the current (wazuh-linux-sensors) project name.
# Covers what container-test.sh cannot: hosts deployed before the rename.
#
# Usage: bash test/marker-test.sh
set -uo pipefail
REPO="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
run() { "$@"; }                      # stand-in for the installer's wrapper
# shellcheck disable=SC1090
source "${REPO}/lib/install-wazuh-agent.sh" 2>/dev/null || true
: "${_LAUREL_LF_BEGIN_RE:?_RE vars not defined}"
fails=0
for project in wazuh-auditd-installer wazuh-linux-sensors; do
  for sensor in LAUREL FALCO; do
    conf="$(mktemp)"
    printf '<ossec_config>\n  <keep>me</keep>\n<!-- BEGIN %s: %s -->\n  <localfile><location>/x</location></localfile>\n<!-- END %s: %s -->\n  <keep>me2</keep>\n</ossec_config>\n' \
      "$project" "$sensor" "$project" "$sensor" > "$conf"
    b="_${sensor}_LF_BEGIN_RE"; e="_${sensor}_LF_END_RE"
    grep -qE "${!b}" "$conf" || { echo "FAIL grep  $project/$sensor"; fails=$((fails+1)); continue; }
    run sed -i -E "\\#${!b}#,\\#${!e}#d" "$conf"
    if grep -q "$sensor" "$conf" || ! grep -q "me2" "$conf"; then
      echo "FAIL sed   $project/$sensor"; cat "$conf"; fails=$((fails+1))
    else
      echo "ok   $project / $sensor block removed, rest intact"
    fi
    rm -f "$conf"
  done
done
# auditd ruleset marker (ERE lives in uninstall.sh)
m=$(grep -oP '(?<=^_AUDITD_RULES_MARKER_RE=").*(?="$)' "${REPO}/lib/uninstall.sh")
for project in wazuh-auditd-installer wazuh-linux-sensors; do
  echo "# ${project}: managed ruleset" | grep -qE "$m" \
    && echo "ok   $project / auditd marker recognised" \
    || { echo "FAIL auditd marker $project"; fails=$((fails+1)); }
done
# a distro ruleset must NOT match
echo "# This file is automatically generated from /etc/audit/rules.d" | grep -qE "$m" \
  && { echo "FAIL distro ruleset matched"; fails=$((fails+1)); } \
  || echo "ok   distro ruleset not claimed"
echo "--- failures: $fails"; exit $((fails > 0))
